"""Churn benchmark: incremental-protocol metrics over the committed churn corpus.

`corpora/churn/` (generated by `tools/gen_churn.py`, fixed seed, committed)
holds baseline Boogie scenarios (4 procedures each, one assert per procedure,
all z3-dischargeable LIA families) plus `expected.json` with the expected
reused/recomputed partition per mutation family:

- `no-op-reorder` (the 100%-hit control group): the churned obligations are
  artifact-level context reorderings - nothing in the identity tuple
  `(spec_ref, semantics_model, program_ref, profile_version)` moves, so every
  obligation must be reused.
- `spec-churn`: a deterministic literal precondition is added to the I2
  contract (mutated procedures only) - the spec artifact ref moves, so those
  obligations must recompute; untouched procedures must still hit.
- `code-churn`: the I3 fragment text is rewritten for mutated procedures -
  the program artifact ref moves (in the M1 VC approximation the obligation
  sequent is invariant to body statements, so the measured effect is exactly
  the identity move: protocol mechanics, not toolchain-evolution fidelity).
- `library-churn`: the target profile version is bumped on every obligation
  (a semantics-library upgrade) - the whole set must recompute.

The measured claim is protocol mechanics under churn. Metrics (all
count-based, no wall-clock, hence reproducible):

- `cache_hit_rate` = reused / obligations (target >= 0.70)
- `churn_survival` = reused / obligations over the churn families only,
  control excluded (target >= 0.30)
- `no_op_hit_rate` = reused / obligations on the control (must be 1.0)
- `fidelity` = fraction of obligations whose observed partition and verdict
  match `expected.json` (must be 1.0)
- `downgrade_rate` = churned obligations that did not stay `discharged`
  (headline metric: the protocol never downgrades guarantees under churn)
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from pathlib import Path

from ..adapters.boogie.lower import ProcedureImport, import_module
from ..artifacts import Obligation, Specification, artifact_id
from ..artifacts.obligation import Sequent
from ..artifacts.terms import Term, const, term_vars, var
from ..ledger import Ledger
from ..store import ContentStore
from .incremental import check_incremental

CORPUS_VERSION = 1
LIBRARY_CHURN_PROFILE = "uvil.boogie@2"
CONTROL_FAMILY = "no-op-reorder"
FAMILIES = ("no-op-reorder", "spec-churn", "code-churn", "library-churn")

CACHE_HIT_TARGET = 0.70
CHURN_SURVIVAL_TARGET = 0.30


@dataclass(frozen=True)
class ScenarioSpec:
    name: str
    family: str
    file: str  # posix relative path under the corpus dir
    mutate: tuple[str, ...]  # procedure names mutated (empty = control/all)


@dataclass
class ScenarioOutcome:
    scenario: str
    family: str
    reused: list[str] = field(default_factory=list)  # proc names
    recomputed: list[str] = field(default_factory=list)  # proc names
    expected: dict[str, str] = field(default_factory=dict)  # proc -> reused|recomputed
    verdicts: dict[str, str] = field(default_factory=dict)  # proc -> status

    @property
    def matches_expected(self) -> bool:
        for proc, want in self.expected.items():
            got = "reused" if proc in self.reused else "recomputed"
            if got != want:
                return False
            if want == "reused" and self.verdicts.get(proc) != "discharged":
                return False
        return True


@dataclass
class BenchResult:
    outcomes: list[ScenarioOutcome] = field(default_factory=list)
    metrics: dict[str, float | int] = field(default_factory=dict)


def load_scenarios(corpus_dir: Path) -> dict[str, ScenarioSpec]:
    manifest = json.loads((corpus_dir / "expected.json").read_text(encoding="utf-8"))
    out: dict[str, ScenarioSpec] = {}
    for name, entry in manifest["scenarios"].items():
        out[name] = ScenarioSpec(
            name=name,
            family=entry["family"],
            file=entry["file"],
            mutate=tuple(entry.get("mutate", [])),
        )
    return out


def _first_var(obl: Obligation) -> str:
    names: set[str] = set()
    for t in [*obl.sequent.context, obl.sequent.goal]:
        names |= term_vars(t)
    return sorted(names)[0]


def _literal_for(tag: str) -> int:
    return int(hashlib.sha256(tag.encode("utf-8")).hexdigest()[:8], 16) % 50 + 1


def mutate_spec(spec: Specification, obl: Obligation, tag: str) -> Specification:
    """spec-churn: add a deterministic literal precondition (moves the I2)."""
    lit = Term(op="ge", args=[var(_first_var(obl)), const(_literal_for(tag))])
    contracts = spec.contracts.model_copy(update={"requires": [*spec.contracts.requires, lit]})
    return spec.model_copy(update={"contracts": contracts})


def mutate_program_fragment(fragment: str, tag: str) -> str:
    """code-churn: rewrite the I3 fragment text (moves the I3 artifact)."""
    return fragment + f"\n  // code-churn {tag}: operand rewritten"


def _churn_scenario(
    scenario: ScenarioSpec,
    procedures: dict[str, ProcedureImport],
) -> tuple[list[Obligation], dict[str, str], dict[str, str]]:
    """Apply the family mutation.

    Returns (churned obligations, expected partition per proc, ref->proc map).
    """
    churned: list[Obligation] = []
    expected: dict[str, str] = {}
    ref_to_proc: dict[str, str] = {}
    for pname in sorted(procedures):
        proc = procedures[pname]
        (obl,) = proc.obligations  # corpus discipline: one assert per procedure
        if scenario.family == CONTROL_FAMILY:
            churned_obl = obl.model_copy(
                update={
                    "sequent": Sequent(
                        context=list(reversed(obl.sequent.context)),
                        goal=obl.sequent.goal,
                        var_sorts=obl.sequent.var_sorts,
                    )
                }
            )
            expected[pname] = "reused"
        elif scenario.family == "library-churn":
            churned_obl = obl.model_copy(update={"target_profile": LIBRARY_CHURN_PROFILE})
            expected[pname] = "recomputed"
        elif pname in scenario.mutate:
            tag = f"{scenario.name}:{pname}"
            if scenario.family == "spec-churn":
                new_spec = mutate_spec(proc.spec, obl, tag)
                churned_obl = obl.model_copy(update={"spec_ref": artifact_id(new_spec)})
            else:
                assert scenario.family == "code-churn"
                assert proc.program.fragment is not None
                new_prog = proc.program.model_copy(
                    update={"fragment": mutate_program_fragment(proc.program.fragment, tag)}
                )
                churned_obl = obl.model_copy(update={"program_ref": artifact_id(new_prog)})
            expected[pname] = "recomputed"
        else:
            churned_obl = obl
            expected[pname] = "reused"
        churned.append(churned_obl)
        ref_to_proc[artifact_id(churned_obl)] = pname
    return churned, expected, ref_to_proc


def run_benchmark(
    corpus_dir: Path,
    state: Path,
    backend: str = "z3",
    timeout_ms: int | None = None,
) -> BenchResult:
    """Prime the cache with each baseline, measure the churned run, score it."""
    scenarios = load_scenarios(corpus_dir)
    store = ContentStore(state)
    ledger = Ledger(state / "ledger.jsonl")
    result = BenchResult()

    for name in sorted(scenarios):
        scenario = scenarios[name]
        source = (corpus_dir / scenario.file).read_text(encoding="utf-8")
        imported = import_module(source, scenario.file)
        assert imported.ok, f"{name}: baseline scenario failed to import"

        # baseline run primes the cache
        baseline = [o for p in imported.procedures.values() for o in p.obligations]
        check_incremental(baseline, store, ledger, backend=backend, timeout_ms=timeout_ms)

        churned, expected, ref_to_proc = _churn_scenario(scenario, imported.procedures)
        measured = check_incremental(churned, store, ledger, backend=backend, timeout_ms=timeout_ms)
        assert measured.result.run is not None
        statuses = {v.obligation_ref: v.status for v in measured.result.run.verdicts}
        outcome = ScenarioOutcome(scenario=name, family=scenario.family, expected=expected)
        outcome.reused = [ref_to_proc[ref] for ref in measured.reused]
        outcome.recomputed = [ref_to_proc[ref] for ref in measured.recomputed]
        for ref, proc in ref_to_proc.items():
            outcome.verdicts[proc] = statuses[ref]
        result.outcomes.append(outcome)

    result.metrics = _metrics(result.outcomes)
    return result


def _metrics(outcomes: list[ScenarioOutcome]) -> dict[str, float | int]:
    total = 0
    reused = 0
    downgraded = 0
    control_total = 0
    control_reused = 0
    churn_total = 0
    churn_reused = 0
    fidelity_matching = 0
    for o in outcomes:
        for proc, status in o.verdicts.items():
            total += 1
            hit = proc in o.reused
            reused += hit
            if status != "discharged":
                downgraded += 1
            if o.family == CONTROL_FAMILY:
                control_total += 1
                control_reused += hit
            else:
                churn_total += 1
                churn_reused += hit
        if o.matches_expected:
            fidelity_matching += len(o.expected)
    return {
        "scenarios": len(outcomes),
        "obligations": total,
        "reused": reused,
        "recomputed": total - reused,
        "cache_hit_rate": reused / total if total else 0.0,
        "no_op_hit_rate": control_reused / control_total if control_total else 1.0,
        "churn_survival": churn_reused / churn_total if churn_total else 1.0,
        "fidelity": fidelity_matching / total if total else 0.0,
        "downgrade_rate": downgraded / total if total else 0.0,
        "cache_hit_target": CACHE_HIT_TARGET,
        "churn_survival_target": CHURN_SURVIVAL_TARGET,
    }


def targets_met(metrics: dict[str, float | int]) -> bool:
    return (
        float(metrics["cache_hit_rate"]) >= CACHE_HIT_TARGET
        and float(metrics["churn_survival"]) >= CHURN_SURVIVAL_TARGET
        and float(metrics["no_op_hit_rate"]) == 1.0
        and float(metrics["fidelity"]) == 1.0
        and float(metrics["downgrade_rate"]) == 0.0
    )


def results_markdown(metrics: dict[str, float | int]) -> str:
    lines = [
        "# Churn benchmark results",
        "",
        "Deterministic metrics over the committed churn corpus (fixed seed;",
        "regenerate with `python tools/gen_churn.py`, reproducible with `uvil bench`).",
        "",
        "| metric | value | target |",
        "|---|---|---|",
        f"| scenarios | {metrics['scenarios']} | - |",
        f"| obligations (churned runs) | {metrics['obligations']} | - |",
        f"| cache-hit rate | {metrics['cache_hit_rate']:.3f} | >= {CACHE_HIT_TARGET} |",
        f"| no-op control hit rate | {metrics['no_op_hit_rate']:.3f} | == 1.0 |",
        f"| churn survival | {metrics['churn_survival']:.3f} | >= {CHURN_SURVIVAL_TARGET} |",
        f"| partition fidelity | {metrics['fidelity']:.3f} | == 1.0 |",
        f"| downgrade rate | {metrics['downgrade_rate']:.3f} | == 0.0 |",
        "",
        "Cache-hit rate = reused / obligations over the churned runs; churn",
        "survival excludes the no-op-reorder control family. Downgrade rate",
        "counts churned obligations that did not stay `discharged`.",
        "",
    ]
    return "\n".join(lines)
